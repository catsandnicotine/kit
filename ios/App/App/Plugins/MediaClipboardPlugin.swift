import UIKit
import UniformTypeIdentifiers
import Capacitor

/// Clipboard media remains file-backed: video bytes never pass through the JavaScript bridge.
@objc(MediaClipboardPlugin)
class MediaClipboardPlugin: CAPPlugin, CAPBridgedPlugin {
    let identifier = "MediaClipboardPlugin"
    let jsName = "MediaClipboard"
    let pluginMethods: [CAPPluginMethod] = [
        CAPPluginMethod(name: "paste", returnType: CAPPluginReturnPromise),
        CAPPluginMethod(name: "copy", returnType: CAPPluginReturnPromise),
    ]
    private var pasting = false
    private let clipboardCache = ClipboardMediaCache()

    @objc func paste(_ call: CAPPluginCall) {
        guard let deckId = call.getString("deckId"), validDeckId(deckId) else {
            call.reject("Couldn’t identify this deck. Reopen it and try again.")
            return
        }
        DispatchQueue.main.async {
            guard !self.pasting else {
                call.reject("A paste is already in progress. Please wait.")
                return
            }
            self.pasting = true
            // Read only here, after an explicit Paste action. iOS owns any consent prompt.
            let providers = UIPasteboard.general.itemProviders
            self.paste(providers, at: 0, into: deckId, saved: [], paths: [], call: call)
        }
    }

    private func paste(_ providers: [NSItemProvider], at index: Int, into deckId: String,
                       saved: [JSObject], paths: [URL], call: CAPPluginCall) {
        guard index < providers.count else {
            pasting = false
            if saved.isEmpty {
                call.reject("The clipboard doesn’t include a photo or video Kit can use. Try Add media instead.")
            } else {
                call.resolve(["items": saved])
            }
            return
        }
        let provider = providers[index]
        // Prefer an actual movie over a poster image offered by the same item.
        let types = provider.registeredTypeIdentifiers
        let movie = types.first { UTType($0)?.conforms(to: .movie) == true }
        let image = types.first { UTType($0)?.conforms(to: .image) == true }
        guard let typeIdentifier = movie ?? image else {
            paste(providers, at: index + 1, into: deckId, saved: saved, paths: paths, call: call)
            return
        }
        let kind = movie == nil ? "image" : "video"
        provider.loadFileRepresentation(forTypeIdentifier: typeIdentifier) { source, error in
            do {
                guard error == nil, let source else { throw self.mediaError("Couldn’t read that clipboard file. Try copying it again or use Add media.") }
                let folder = try self.mediaDirectory(deckId)
                let declared = UTType(typeIdentifier)
                let sourceType = UTType(filenameExtension: source.pathExtension)
                let expected: UTType = kind == "video" ? .movie : .image
                let extensionName = sourceType?.conforms(to: expected) == true
                    ? source.pathExtension.lowercased() : declared?.preferredFilenameExtension
                guard let extensionName, extensionName.range(of: "^[a-z0-9]{1,8}$", options: .regularExpression) != nil else {
                    throw self.mediaError("This clipboard file has no usable media format. Try Add media instead.")
                }
                let filename = "user_\(UUID().uuidString.lowercased()).\(extensionName)"
                let destination = folder.appendingPathComponent(filename)
                let size = try source.resourceValues(forKeys: [.fileSizeKey]).fileSize ?? 0
                guard size > 0 else { throw self.mediaError("The clipboard file is empty. Copy it again or use Add media.") }
                // NSItemProvider deletes its temporary file when this callback returns.
                // Finish the independent local copy before dispatching back to the UI queue.
                do { try FileManager.default.copyItem(at: source, to: destination) }
                catch { try? FileManager.default.removeItem(at: destination); throw error }
                let item: JSObject = ["filename": filename, "url": destination.absoluteString, "kind": kind]
                DispatchQueue.main.async {
                    self.paste(providers, at: index + 1, into: deckId, saved: saved + [item], paths: paths + [destination], call: call)
                }
            } catch {
                // Only files generated by this unsuccessful operation may be removed.
                for path in paths { try? FileManager.default.removeItem(at: path) }
                DispatchQueue.main.async {
                    self.pasting = false
                    call.reject("Couldn’t paste that media. Check your device’s storage, or try Add media. Your card is unchanged.")
                }
            }
        }
    }

    @objc func copy(_ call: CAPPluginCall) {
        guard let deckId = call.getString("deckId"), validDeckId(deckId),
              let filename = call.getString("filename"), validFilename(filename),
              let kind = call.getString("kind"), kind == "image" || kind == "video" else {
            call.reject("Couldn’t identify that attachment. Reopen the card and try again.")
            return
        }
        DispatchQueue.global(qos: .userInitiated).async {
            var snapshotFolder: URL?
            do {
                let original = try self.copySource(deckId: deckId, filename: filename, displayUrl: call.getString("displayUrl") ?? "")
                guard let type = UTType(filenameExtension: original.pathExtension),
                      type.conforms(to: kind == "video" ? .movie : .image) else {
                    throw self.mediaError("Unsupported media format")
                }
                // Keep copied content available independently of later card/deck edits.
                let cache = try self.clipboardCache.makeSnapshotFolder()
                snapshotFolder = cache
                let snapshot = cache.appendingPathComponent(filename)
                try FileManager.default.copyItem(at: original, to: snapshot)
                let provider = NSItemProvider()
                provider.suggestedName = filename
                let snapshots = self.clipboardCache
                provider.registerFileRepresentation(forTypeIdentifier: type.identifier, fileOptions: [], visibility: .all) { completion in
                    snapshots.beginRead(cache)
                    defer { snapshots.endRead(cache) }
                    // Without openInPlace, NSItemProvider finishes its independent copy
                    // before this load handler returns. Keep our snapshot through that copy.
                    completion(snapshot, false, nil)
                    return nil
                }
                DispatchQueue.main.async {
                    // Writing the selected attachment does not read the user's clipboard.
                    UIPasteboard.general.itemProviders = [provider]
                    snapshots.didPublish(cache)
                    call.resolve()
                }
            } catch {
                if let snapshotFolder { self.clipboardCache.cancelSnapshot(snapshotFolder) }
                call.reject("Couldn’t copy that media. Make sure its original file is available on this device, then try again.")
            }
        }
    }

    private func mediaDirectory(_ deckId: String) throws -> URL {
        let folder = FileManager.default.urls(for: .documentDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("media", isDirectory: true).appendingPathComponent(deckId, isDirectory: true)
        try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        return folder
    }

    private func copySource(deckId: String, filename: String, displayUrl: String) throws -> URL {
        let stored = try mediaDirectory(deckId).appendingPathComponent(filename)
        if isRegularFile(stored) { return stored }
        // The optional built-in art deck serves its original files from the app bundle.
        if deckId == "e0a57e12-0000-4000-8000-000000000001", let url = URL(string: displayUrl),
           (url.scheme == "capacitor" || url.scheme == "http" || url.scheme == "https"),
           url.host == "localhost", url.lastPathComponent == filename,
           url.path.hasPrefix("/decks/jesus-paintings/"),
           let resources = Bundle.main.resourceURL {
            let publicFolder = resources.appendingPathComponent("public", isDirectory: true)
            let bundled = publicFolder.appendingPathComponent(String(url.path.dropFirst())).standardizedFileURL
            if bundled.path.hasPrefix(publicFolder.path + "/"), isRegularFile(bundled) { return bundled }
        }
        throw mediaError("Media unavailable")
    }

    private func isRegularFile(_ url: URL) -> Bool {
        guard let values = try? url.resourceValues(forKeys: [.isRegularFileKey, .isSymbolicLinkKey, .fileSizeKey]) else { return false }
        return values.isRegularFile == true && values.isSymbolicLink != true && (values.fileSize ?? 0) > 0
    }

    private func validDeckId(_ value: String) -> Bool {
        value.range(of: "^[a-zA-Z0-9_-]{1,160}$", options: .regularExpression) != nil
    }

    private func validFilename(_ value: String) -> Bool {
        !value.isEmpty && value != "." && value != ".." && value.count <= 255
            && value.rangeOfCharacter(from: CharacterSet(charactersIn: "/\\").union(.controlCharacters)) == nil
    }

    private func mediaError(_ description: String) -> NSError {
        NSError(domain: "KitMediaClipboard", code: 1, userInfo: [NSLocalizedDescriptionKey: description])
    }
}

/// Keep a small history without reading the system pasteboard to discover its owner.
/// Provider closures retain this store independently of the Capacitor plugin lifetime.
private final class ClipboardMediaCache {
    private let lock = NSLock()
    private let root = FileManager.default.urls(for: .cachesDirectory, in: .userDomainMask)[0]
        .appendingPathComponent("KitClipboard", isDirectory: true)
    private var pending = Set<URL>()
    private var current: URL?
    private var inFlight: [URL: Int] = [:]

    func makeSnapshotFolder() throws -> URL {
        let folder = root.appendingPathComponent(UUID().uuidString, isDirectory: true)
        lock.lock()
        defer { lock.unlock() }
        try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        pending.insert(folder)
        return folder
    }

    func didPublish(_ folder: URL) {
        lock.lock()
        current = folder
        pending.remove(folder)
        lock.unlock()
        prune()
    }

    func cancelSnapshot(_ folder: URL) {
        lock.lock()
        pending.remove(folder)
        if current != folder && inFlight[folder] == nil {
            do { try FileManager.default.removeItem(at: folder) }
            catch { NSLog("Kit clipboard could not remove an incomplete owned snapshot") }
        }
        lock.unlock()
        prune()
    }

    func beginRead(_ folder: URL) {
        lock.lock()
        inFlight[folder, default: 0] += 1
        lock.unlock()
    }

    func endRead(_ folder: URL) {
        lock.lock()
        if let count = inFlight[folder], count > 1 { inFlight[folder] = count - 1 }
        else { inFlight.removeValue(forKey: folder) }
        lock.unlock()
        prune()
    }

    private func prune() {
        lock.lock()
        defer { lock.unlock() }
        do {
            let keys: Set<URLResourceKey> = [.isDirectoryKey, .isSymbolicLinkKey, .creationDateKey]
            let children = try FileManager.default.contentsOfDirectory(at: root, includingPropertiesForKeys: Array(keys), options: [.skipsHiddenFiles])
            let folders: [(url: URL, created: Date)] = children.compactMap { url in
                guard UUID(uuidString: url.lastPathComponent) != nil,
                      let values = try? url.resourceValues(forKeys: keys),
                      values.isDirectory == true, values.isSymbolicLink != true else { return nil }
                return (url, values.creationDate ?? .distantPast)
            }.sorted { $0.created > $1.created }
            // Keep the latest eight plus anything being published, currently owned,
            // or actively copied by another process. A finished read retries pruning.
            // Directory URLs obtained from enumeration can differ in trailing slash
            // from appendingPathComponent(isDirectory:true), so compare path components.
            var keep = Set(folders.prefix(8).map { cacheKey($0.url) })
            keep.formUnion(pending.map(cacheKey))
            keep.formUnion(inFlight.keys.map(cacheKey))
            if let current { keep.insert(cacheKey(current)) }
            for folder in folders where !keep.contains(cacheKey(folder.url)) {
                try FileManager.default.removeItem(at: folder.url)
            }
        } catch {
            // Cache cleanup must never invalidate a successful clipboard operation.
            NSLog("Kit clipboard cache cleanup will retry after the next copy")
        }
    }

    private func cacheKey(_ url: URL) -> String {
        url.standardizedFileURL.pathComponents.joined(separator: "/")
    }
}
