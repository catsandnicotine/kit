// Download eligible images sequentially, then create the app's checked manifest.
// Chicago requests are separated by at least one second, per its API guidance.
import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../', import.meta.url));
const imageDir = path.join(root, 'public/decks/jesus-paintings');
const cache = process.env.KIT_ART_CACHE ?? '/tmp/kit-jesus-catalogue';
await fs.mkdir(imageDir, { recursive: true });
const catalogue = JSON.parse(await fs.readFile(path.join(root, 'scripts/jesus-paintings/records.json'), 'utf8'));
let previousFailures = [];
try {
  previousFailures = JSON.parse(await fs.readFile(path.join(imageDir, 'catalogue.json'), 'utf8')).exclusions?.unavailableImages ?? [];
} catch { /* first run */ }
const failedImages = new Map(previousFailures.map(entry => [entry.id, entry]));
const retryUnavailable = process.argv.includes('--retry-unavailable');
const exclusions = JSON.parse(await fs.readFile(new URL('exclusions.json', import.meta.url), 'utf8'));
const included = [];
const unavailable = [];
const checksums = {};
const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
for (const art of catalogue.paintings) {
  if (exclusions[art.id]) { console.log(`Excluded ${art.id}: ${exclusions[art.id]}`); continue; }
  if (art.rights !== 'CC0' || !art.rightsEvidence) throw new Error(`Missing rights evidence: ${art.id}`);
  const filename = `jesus-${art.id}.jpg`;
  const dest = path.join(imageDir, filename);
  try {
    try { await fs.access(dest); } catch {
      if (!retryUnavailable && failedImages.has(art.id)) {
        unavailable.push(failedImages.get(art.id));
        continue;
      }
      const response = await fetch(art.imageUrl, { signal: AbortSignal.timeout(60000) });
      if (art.id.startsWith('aic-')) await pause(1100);
      if (!response.ok) throw new Error(`HTTP ${response.status}`);
      const bytes = Buffer.from(await response.arrayBuffer());
      if (bytes[0] !== 0xff || bytes[1] !== 0xd8 || bytes.length < 3000) throw new Error('Museum did not return a valid JPEG');
      const original = path.join(cache, filename);
      await fs.writeFile(original, bytes);
      // macOS sips preserves aspect ratio, constrains the longest side, and
      // writes a compact local JPEG. No generated or reconstructed paintings.
      const temp = dest + '.tmp.jpg';
      execFileSync('/usr/bin/sips', ['-s', 'format', 'jpeg', '-s', 'formatOptions', '78', '-Z', '1200', original, '--out', temp], { stdio: 'ignore' });
      await fs.rename(temp, dest);
      if (!art.id.startsWith('aic-')) await pause(150);
    }
    const bytes = await fs.readFile(dest);
    if (bytes[0] !== 0xff || bytes[1] !== 0xd8) throw new Error('Invalid bundled JPEG');
    checksums[filename] = crypto.createHash('sha256').update(bytes).digest('hex');
    included.push(art);
    if (included.length % 20 === 0) console.log(`${included.length}/${catalogue.paintings.length} images ready`);
  } catch (error) {
    unavailable.push({ id: art.id, imageUrl: art.imageUrl, reason: error.message });
    console.warn(`Image unavailable: ${art.id}: ${error.message}`);
  }
}
catalogue.paintings = included;
catalogue.exclusions = { subjectReview: exclusions, unavailableImages: unavailable };
const text = JSON.stringify(catalogue, null, 2);
await fs.writeFile(path.join(root, 'src/data/jesusPaintings.ts'), `// Museum catalogue generated by scripts/jesus-paintings.\nimport type { JesusPaintingCatalogue } from '../types/jesusPaintings';\nexport const jesusPaintingCatalogue: JesusPaintingCatalogue = ${text};\n`);
await fs.writeFile(path.join(root, 'src/data/jesusPaintingFiles.ts'), `// Generated from downloaded and verified images.\nexport const JESUS_PAINTING_FILES: readonly string[] = ${JSON.stringify(included.map(art => `jesus-${art.id}.jpg`), null, 2)};\n`);
await fs.writeFile(path.join(imageDir, 'catalogue.json'), text + '\n');
await fs.writeFile(path.join(imageDir, 'checksums.json'), JSON.stringify(checksums, null, 2) + '\n');
console.log(`Bundled ${included.length} paintings. ${unavailable.length} images unavailable.`);
